export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 20,
  className = "",
  title,
}: {
  name: IconName;
  size?: number;
  className?: string;
  title?: string;
}) {
  const props = {
    className: `icon ${className}`,
    style: { width: size, height: size },
    dangerouslySetInnerHTML: { __html: ICONS[name] },
  };
  return title ? <span role="img" aria-label={title} {...props} /> : <span aria-hidden {...props} />;
}

export function IconButton({
  name,
  label,
  onClick,
  size = 20,
  className = "",
  disabled,
  active,
  href,
}: {
  name: IconName;
  label: string;
  onClick?: (e: React.MouseEvent) => void;
  size?: number;
  className?: string;
  disabled?: boolean;
  active?: boolean;
  href?: string;
}) {
  const cls = `icon-btn ${active ? "active " : ""}${className}`;
  if (href) {
    return (
      <a className={cls} href={href} title={label} aria-label={label} target="_blank" rel="noopener noreferrer">
        <Icon name={name} size={size} />
      </a>
    );
  }
  return (
    <button type="button" className={cls} onClick={onClick} title={label} aria-label={label} disabled={disabled}>
      <Icon name={name} size={size} />
    </button>
  );
}
